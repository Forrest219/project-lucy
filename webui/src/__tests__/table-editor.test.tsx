const LONG_QUALIFIED_NAME =
  "dataforai.superstore_orders_with_a_very_long_business_name_for_layout_regression";
const OVERLAY_TOOLTIP = "修改将写入独立 overlay 文件：semantic-layer/mysql-aliyun/superstore_orders.yaml";

function renderEditor(path = "/catalog/mysql-aliyun/dataforai/superstore_orders") {
  const client = new QueryClient({
    defaultOptions: {
      queries: { retry: false }
    }
  });

  render(
    <QueryClientProvider client={client}>
      <MemoryRouter initialEntries={[path]}>
        <Routes>
          <Route path="/catalog/:conn/:schema/:table" element={<TableEditor />} />
        </Routes>
      </MemoryRouter>
    </QueryClientProvider>
  );
}

async function openManualSemanticEditor() {
  const disclosure = await screen.findByTestId("manual-semantic-disclosure");
  if (!disclosure.hasAttribute("open")) {
    fireEvent.click(within(disclosure).getByText("高级：手工维护语义字段"));
  }
  return disclosure;
}

function buildSourceDetail() {
  return {
    model: {
      conn: "mysql-aliyun",
      schema: "dataforai",
      table: "superstore_orders",
      filePath: "semantic-layer/mysql-aliyun/_schema/dataforai.yaml",
      qualifiedName: LONG_QUALIFIED_NAME,
      descriptions: {
        human: "Aggregate order rows for revenue analytics",
        ai: "AI-suggested table description"
      },
      grain: ["order_key"],
      columns: [
        {
          name: "order_key",
          type: "string",
          pk: true,
          nullable: false,
          descriptions: {
            ai: "Business key grouping multiple line items belonging to one order."
          }
        },
        {
          name: "row_id",
          type: "string",
          pk: true,
          nullable: false,
          descriptions: {
            human: "Unique row identifier",
            ai: "Unique row identifier generated by the source system."
          }
        },
        {
          name: "order_date",
          type: "time",
          nullable: true,
          descriptions: {
            ai: "Date when the order was placed."
          }
        }
      ],
      measures: [{ name: "total_sales", expr: "sum(sales)", description: "Total sales" }],
      segments: [],
      joins: [],
      unknownKeys: []
    },
    rawYaml: "table: dataforai.superstore_orders\n",
    completion: "partial"
  };
}

type FetchHandlers = {
  failSave?: boolean;
  failPreview?: boolean;
  candidates?: unknown;
};

function stubEditorFetch({ failSave = false, failPreview = false, candidates }: FetchHandlers = {}) {
  const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = String(input);
    if (url === "/api/sources") {
      return new Response(
        JSON.stringify({
          ok: true,
          data: {
            tables: [
              {
                conn: "mysql-aliyun",
                schema: "dataforai",
                table: "superstore_orders",
                filePath: "semantic-layer/mysql-aliyun/_schema/dataforai.yaml",
                columnCount: 3,
                columnNames: ["order_key", "row_id", "order_date"],
                hasTableDesc: true,
                hasGrain: true,
                measureCount: 1,
                joinCount: 0,
                wikiRefCount: 0,
                completion: "partial",
                mtime: "2026-06-15T00:00:00.000Z"
              }
            ]
          }
        })
      );
    }
    if (url === "/api/sources/mysql-aliyun/dataforai/superstore_orders" && !init) {
      return new Response(JSON.stringify({ ok: true, data: buildSourceDetail() }));
    }
    if (url === "/api/joins/candidates" && (!init || init.method === undefined)) {
      return new Response(
        JSON.stringify({
          ok: true,
          data: {
            version: 1,
            candidates: candidates ?? []
          }
        })
      );
    }
    if (url === "/api/sources/mysql-aliyun/dataforai/superstore_orders" && init?.method === "PUT") {
      const body = JSON.parse(String(init.body));
      if (body.dryRun) {
        if (failPreview) {
          return new Response(
            JSON.stringify({ ok: false, error: { code: "PREVIEW_FAILED", message: "preview denied" } }),
            { status: 500 }
          );
        }
        return new Response(
          JSON.stringify({
            ok: true,
            data: {
              diff: "+ human: Human column description",
              proposedYaml: "proposed",
              files: [
                {
                  filePath: "semantic-layer/mysql-aliyun/superstore_orders.yaml",
                  diff: "+ human",
                  proposedYaml: "proposed"
                }
              ]
            }
          })
        );
      }
      if (failSave) {
        return new Response(
          JSON.stringify({ ok: false, error: { code: "SAVE_FAILED", message: "disk denied" } }),
          { status: 500 }
        );
      }
      return new Response(
        JSON.stringify({
          ok: true,
          data: {
            written: true,
            validation: { ok: true, exitCode: 0, stdout: "", stderr: "" },
            changedFiles: []
          }
        })
      );
    }
    if (url === "/api/sources/mysql-aliyun/dataforai/superstore_orders/import" && init?.method === "POST") {
      const body = JSON.parse(String(init.body));
      if (body.dryRun) {
        return new Response(
          JSON.stringify({
            ok: true,
            data: {
              diff: "- descriptions:\n+ descriptions:",
              proposedYaml: body.yaml,
              files: [
                {
                  filePath: "semantic-layer/mysql-aliyun/_schema/dataforai.yaml",
                  diff: "- descriptions:\n+ descriptions:",
                  proposedYaml: body.yaml
                }
              ]
            }
          })
        );
      }
      return new Response(
        JSON.stringify({
          ok: true,
          data: {
            written: true,
            validation: { ok: true, exitCode: 0, stdout: "", stderr: "" },
            changedFiles: []
          }
        })
      );
    }
    if (url === "/api/sources/mysql-aliyun/dataforai/superstore_orders/validate" && init?.method === "POST") {
      return new Response(
        JSON.stringify({
          ok: true,
          data: { ok: true, exitCode: 0, stdout: "ok", stderr: "", issues: [] }
        })
      );
    }
    if (url === "/api/joins/candidates" && init?.method === "PUT") {
      const body = JSON.parse(String(init.body));
      return new Response(
        JSON.stringify({
          ok: true,
          data: {
            version: 1,
            candidates: body.candidates ?? []
          }
        })
      );
    }
    return new Response(
      JSON.stringify({ ok: false, error: { code: "NOT_FOUND", message: url } }),
      { status: 404 }
    );
  });
  vi.stubGlobal("fetch", fetchMock);
  return fetchMock;
}

