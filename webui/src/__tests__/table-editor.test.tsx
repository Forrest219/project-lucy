    expect(
      await screen.findByDisplayValue(
        "Business key grouping multiple line items belonging to one order."
      )
    ).toBeInTheDocument();

    // Dry-run patch writes only descriptions.human (not the AI bucket)
    await waitFor(() => {
      const putCall = fetchMock.mock.calls.find(
        (call) =>
          call[1]?.method === "PUT" &&
          JSON.parse(String(call[1]?.body)).dryRun === true &&
          JSON.parse(String(call[1]?.body)).patch.columns?.some(
            (column: { name: string; description: string }) =>
              column.name === "order_key" &&
              column.description === "Business key grouping multiple line items belonging to one order."
          )
      );
      expect(putCall).toBeTruthy();
      const body = JSON.parse(String(putCall?.[1]?.body));
      expect(body.dryRun).toBe(true);
      expect(body.patch.columns).toContainEqual({
        name: "order_key",
        description: "Business key grouping multiple line items belonging to one order."
      });
    });
