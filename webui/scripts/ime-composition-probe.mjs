// ─── In-page instrumentation ─────────────────────────────────────────────────

/**
 * In-page instrumentation.
 *
 * It MUST be installed **before** React mounts: React's `trackValueOnNode`
 * captures the prototype's `value` setter at mount time and installs its own
 * instance-level accessor that delegates to it. Patching the prototype after
 * mount would therefore miss every write React makes — the counter would read
 * 0 even when the composition was being broken.
 */
const INSTALL_PROBE_SCRIPT = `(() => {
  const proto = HTMLInputElement.prototype;
  if (!window.__imeProbeInstalled) {
    window.__imeProbeInstalled = true;
    const desc = Object.getOwnPropertyDescriptor(proto, "value");
    const defaultDesc = Object.getOwnPropertyDescriptor(proto, "defaultValue");
    const writes = [];
    const defaultWrites = [];
    const compositions = [];
    const trace = [];
    Object.defineProperty(proto, "value", {
      configurable: true,
      enumerable: desc.enumerable,
      get() { return desc.get.call(this); },
      set(value) {
        writes.push({ target: this, value: String(value) });
        desc.set.call(this, value);
      }
    });
    if (defaultDesc) {
      Object.defineProperty(proto, "defaultValue", {
        configurable: true,
        enumerable: defaultDesc.enumerable,
        get() { return defaultDesc.get.call(this); },
        set(value) {
          defaultWrites.push({ target: this, value: String(value) });
          defaultDesc.set.call(this, value);
        }
      });
    }
    const label = (node) => (node && node.getAttribute)
      ? (node.getAttribute("aria-label") || node.getAttribute("data-testid") || node.tagName)
      : "?";
    document.addEventListener("compositionstart", (event) => {
      compositions.push(event.target);
      trace.push({ t: "compositionstart", el: label(event.target), value: event.target.value });
    }, true);
    document.addEventListener("compositionend", (event) => {
      trace.push({ t: "compositionend", el: label(event.target), value: event.target.value });
    }, true);
    document.addEventListener("compositionupdate", (event) => {
      trace.push({ t: "compositionupdate", el: label(event.target), value: event.target.value, data: event.data });
    }, true);
    document.addEventListener("input", (event) => {
      trace.push({ t: "input", el: label(event.target), value: event.target.value, isComposing: event.isComposing, data: event.data });
    }, true);
    window.__imeProbeState = { writes, defaultWrites, compositions, trace };
  }
  const state = window.__imeProbeState;
  window.__imeProbe = {
    reset() { state.writes.length = 0; state.defaultWrites.length = 0; state.compositions.length = 0; state.trace.length = 0; },
    read(selector) {
      const element = document.querySelector(selector);
      if (!element) {
        return { found: false };
      }
      return {
        found: true,
        value: element.value,
        compositionStarts: state.compositions.filter((t) => t === element).length,
        valueWrites: state.writes.filter((w) => w.target === element).length,
        totalValueWrites: state.writes.length,
        defaultValueWrites: state.defaultWrites.filter((w) => w.target === element).length,
        totalDefaultValueWrites: state.defaultWrites.length,
        focused: document.activeElement === element,
        activeElementLabel: document.activeElement
          ? (document.activeElement.getAttribute("aria-label")
            || document.activeElement.getAttribute("data-testid")
            || document.activeElement.tagName)
          : null,
        trace: state.trace.slice()
      };
    }
  };
  return "installed";
})()`;

// ─── Minimal CDP client ──────────────────────────────────────────────────────

class CdpClient {
  constructor(socket) {
    this.socket = socket;
    this.nextId = 1;
    this.pending = new Map();
    this.listeners = new Map();
    socket.addEventListener("message", (event) => {
      let message;
      try {
        message = JSON.parse(event.data);
      } catch {
        return;
      }
      if (message.id !== undefined) {
        const entry = this.pending.get(message.id);
        if (!entry) return;
        this.pending.delete(message.id);
        if (message.error) entry.reject(new Error(`${message.error.message} (${message.error.code})`));
        else entry.resolve(message.result);
        return;
      }
      const handlers = this.listeners.get(message.method) ?? [];
      for (const handler of handlers) handler(message.params);
    });
  }

  static async connect(url) {
    const socket = new WebSocket(url);
    await new Promise((resolve, reject) => {
      socket.addEventListener("open", resolve, { once: true });
      socket.addEventListener("error", () => reject(new Error(`cannot connect to ${url}`)), { once: true });
    });
    return new CdpClient(socket);
  }

  send(method, params = {}) {
    const id = this.nextId++;
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject });
      this.socket.send(JSON.stringify({ id, method, params }));
      setTimeout(() => {
        if (!this.pending.has(id)) return;
        this.pending.delete(id);
        reject(new Error(`CDP timeout: ${method}`));
      }, 30000);
    });
  }

  on(event, handler) {
    const handlers = this.listeners.get(event) ?? [];
    handlers.push(handler);
    this.listeners.set(event, handlers);
  }

  close() {
    try {
      this.socket.close();
    } catch {
      // ignore
    }
  }
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function waitForHttp(url, timeoutMs, label, { json = true } = {}) {
  const deadline = Date.now() + timeoutMs;
  let lastError = null;
  while (Date.now() < deadline) {
    try {
      const response = await fetch(url);
      if (response.ok) {
        if (!json) return true;
        const text = await response.text();
        try {
          return JSON.parse(text);
        } catch {
          lastError = new Error(`${url} did not return JSON`);
        }
      } else {
        lastError = new Error(`${url} responded ${response.status}`);
      }
    } catch (error) {
      lastError = error;
    }
    await sleep(200);
  }
  throw new Error(`${label} did not become ready: ${lastError ? lastError.message : "timeout"}`);
}

// ─── Chrome ──────────────────────────────────────────────────────────────────

function launchChrome(userDataDir) {
  const child = spawn(
    CHROME_BINARY,
    [
      "--headless=new",
      `--remote-debugging-port=${CDP_PORT}`,
      `--user-data-dir=${userDataDir}`,
      "--no-first-run",
      "--no-default-browser-check",
      "--disable-gpu",
      "--disable-dev-shm-usage",
      "--window-size=1600,1200",
      "about:blank"
    ],
    { stdio: ["ignore", "pipe", "pipe"] }
  );
  const logs = [];
  child.stdout?.on("data", (chunk) => logs.push(String(chunk)));
  child.stderr?.on("data", (chunk) => logs.push(String(chunk)));
  child.on("error", (error) => logs.push(`spawn error: ${error.message}`));
  return { child, logs };
}

async function connectToPageTarget() {
  const version = await waitForHttp(`http://127.0.0.1:${CDP_PORT}/json/version`, 30000, "Chrome");
  const list = await waitForHttp(`http://127.0.0.1:${CDP_PORT}/json/list`, 30000, "Chrome target list");
  const page = list.find((entry) => entry.type === "page");
  if (!page) throw new Error("no page target exposed by Chrome");
  const cdp = await CdpClient.connect(page.webSocketDebuggerUrl);
  return { cdp, version };
}

// ─── Probe helpers ───────────────────────────────────────────────────────────

async function evaluate(cdp, expression) {
  const result = await cdp.send("Runtime.evaluate", {
    expression,
    returnByValue: true,
    awaitPromise: true
  });
  if (result.exceptionDetails) {
    throw new Error(
      `page exception: ${result.exceptionDetails.exception?.description ?? result.exceptionDetails.text}`
    );
  }
  return result.result?.value;
}

async function waitForElement(cdp, selector, timeoutMs = 15000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const found = await evaluate(
      cdp,
      `Boolean(document.querySelector(${JSON.stringify(selector)}))`
    );
    if (found) return true;
    await sleep(150);
  }
  return false;
}

async function navigate(cdp, url, currentUrl) {
  const next = new URL(url);
  const current = currentUrl ? new URL(currentUrl) : null;
  const sameDocument =
    current && current.origin === next.origin && current.pathname === next.pathname;
  if (sameDocument) {
    // Only the hash differs → same-document navigation, no reload.
    await evaluate(cdp, `location.hash = ${JSON.stringify(next.hash)}; true`);
    await sleep(500);
    return url;
  }
  await cdp.send("Page.navigate", { url });
  await new Promise((resolve) => {
    const timer = setTimeout(resolve, 20000);
    cdp.on("Page.loadEventFired", () => {
      clearTimeout(timer);
      resolve();
    });
  });
  await sleep(600);
  return url;
}

/**
 * Drive one IME composition sequence and read the counters back.
 * The sequence is the one the spec pins: zhong → zhongwen → 中文.
 */
async function runImeSequence(cdp, selector) {
  await evaluate(cdp, "window.__imeProbe ? (window.__imeProbe.reset(), true) : false");
  await evaluate(
    cdp,
    `(() => { const el = document.querySelector(${JSON.stringify(selector)}); if (!el) return false; el.focus(); el.setSelectionRange(el.value.length, el.value.length); return true; })()`
  );

  const steps = [
    { text: "zhong", selectionStart: 5, selectionEnd: 5 },
    { text: "zhongwen", selectionStart: 8, selectionEnd: 8 },
    { text: "中文", selectionStart: 2, selectionEnd: 2 }
  ];
  for (const step of steps) {
    await cdp.send("Input.imeSetComposition", step);
    // Give React Router a chance to commit the URL and re-render — this is the
    // window in which the URL-driven implementation writes node.value back.
    await sleep(150);
  }

  return evaluate(cdp, `window.__imeProbe.read(${JSON.stringify(selector)})`);
}

function evaluateResult(target, result) {
  const healthy =
    result &&
    result.found === true &&
    result.compositionStarts === 1 &&
    result.value === "中文" &&
    result.valueWrites === 0 &&
    result.focused === true;
  return {
    id: target.id,
    page: target.page,
    route: target.route,
    selector: target.selector,
    urlParam: target.param ?? null,
    expected: target.expected ?? "pass",
    compositionStarts: result?.compositionStarts ?? null,
    finalValue: result?.value ?? null,
    valueWrites: result?.valueWrites ?? null,
    totalValueWrites: result?.totalValueWrites ?? null,
    defaultValueWrites: result?.defaultValueWrites ?? null,
    totalDefaultValueWrites: result?.totalDefaultValueWrites ?? null,
    focusKept: result?.focused ?? null,
    activeElementLabel: result?.activeElementLabel ?? null,
    trace: (result?.trace ?? []).slice(0, 80),
    ok: healthy
  };
}

// ─── Runner ──────────────────────────────────────────────────────────────────

async function run() {
  const results = [];
  const notes = [];
  let chromeVersion = null;
  let viteProcess = null;
  let chrome = null;
  let userDataDir = null;
  let cdp = null;

  const probeHtmlPath = path.join(webuiRoot, PROBE_HTML);
  const probeEntryPath = path.join(webuiRoot, PROBE_ENTRY);

  try {
    if (!existsSync(CHROME_BINARY)) {
      throw new Error(`system Chrome not found at ${CHROME_BINARY}`);
    }

    // 1) temporary vite entry with the REAL page components
    writeFileSync(probeHtmlPath, PROBE_HTML_SOURCE, "utf8");
    writeFileSync(probeEntryPath, PROBE_ENTRY_SOURCE, "utf8");
    notes.push(`临时入口已生成：${PROBE_HTML} + ${PROBE_ENTRY}（跑完删除）`);

    // 2) vite dev server
    viteProcess = spawn(
      path.join(webuiRoot, "node_modules", ".bin", "vite"),
      ["--port", String(VITE_PORT), "--strictPort", "--host", "127.0.0.1"],
      { cwd: webuiRoot, stdio: ["ignore", "pipe", "pipe"] }
    );
    const viteLogs = [];
    viteProcess.stdout?.on("data", (chunk) => viteLogs.push(String(chunk)));
    viteProcess.stderr?.on("data", (chunk) => viteLogs.push(String(chunk)));
    await waitForHttp(`http://127.0.0.1:${VITE_PORT}/${PROBE_HTML}`, 60000, "vite dev server", { json: false });
    notes.push(`vite dev server: http://127.0.0.1:${VITE_PORT}/${PROBE_HTML}`);

    // 3) Chrome
    userDataDir = mkdtempSync(path.join(tmpdir(), "lucy-ime-probe-"));
    chrome = launchChrome(userDataDir);
    const connected = await connectToPageTarget();
    cdp = connected.cdp;
    chromeVersion = connected.version.Browser ?? null;
    notes.push(`Chrome: ${chromeVersion}`);

    await cdp.send("Page.enable");
    await cdp.send("Runtime.enable");
    // The instrumentation has to be in place before React mounts, otherwise
    // React's own value tracker swallows every write we want to count.
    await cdp.send("Page.addScriptToEvaluateOnNewDocument", {
      source: INSTALL_PROBE_SCRIPT
    });

    // 4) each target
    let currentUrl = null;
    for (const target of TARGETS) {
      const targetUrl = `http://127.0.0.1:${VITE_PORT}/${PROBE_HTML}#${target.route}`;
      if (currentUrl !== targetUrl) {
        currentUrl = await navigate(cdp, targetUrl, currentUrl);
      }
      if (target.advanced) {
        // The advanced filter panel must be open before those inputs exist.
        await evaluate(
          cdp,
          `(() => { const b = document.querySelector('[data-testid="audit-advanced-filters-toggle"]'); if (b && b.getAttribute("aria-expanded") !== "true") b.click(); return true; })()`
        );
        await sleep(400);
      }
      const present = await waitForElement(cdp, target.selector);
      if (!present) {
        results.push({
          id: target.id,
          page: target.page,
          route: target.route,
          selector: target.selector,
          expected: "pass",
          ok: false,
          error: "selector not found on the page"
        });
        continue;
      }
      const raw = await runImeSequence(cdp, target.selector);
      results.push(evaluateResult(target, raw));
    }

    // 5) controls on the very same page
    const controlRoute = "/admin/audit?view=turns";
    currentUrl = await navigate(
      cdp,
      `http://127.0.0.1:${VITE_PORT}/${PROBE_HTML}#${controlRoute}`,
      currentUrl
    );
    const controlPresent = await waitForElement(cdp, CONTROL_SELECTOR);
    if (!controlPresent) {
      results.push({
        id: "control-local-state",
        page: "ProbeControl",
        route: controlRoute,
        selector: CONTROL_SELECTOR,
        expected: "pass",
        ok: false,
        error: "control input not found"
      });
    } else {
      const raw = await runImeSequence(cdp, CONTROL_SELECTOR);
      results.push(
        evaluateResult(
          {
            id: "control-local-state",
            page: "ProbeControl",
            route: controlRoute,
            selector: CONTROL_SELECTOR,
            param: null,
            expected: "pass"
          },
          raw
        )
      );
    }

    // 6) URL-driven control — the pre-fix shape. The probe MUST detect the
    //    difference here, otherwise "everything passed" would only mean the
    //    probe cannot measure anything.
    const urlControlPresent = await waitForElement(cdp, URL_CONTROL_SELECTOR);
    if (!urlControlPresent) {
      results.push({
        id: "control-url-driven",
        page: "ProbeControl",
        route: controlRoute,
        selector: URL_CONTROL_SELECTOR,
        expected: "detect-defect",
        ok: false,
        error: "url-driven control input not found"
      });
    } else {
      const raw = await runImeSequence(cdp, URL_CONTROL_SELECTOR);
      const observed = evaluateResult(
        {
          id: "control-url-driven",
          page: "ProbeControl",
          route: controlRoute,
          selector: URL_CONTROL_SELECTOR,
          param: "probe_ctrl",
          expected: "detect-defect"
        },
        raw
      );
      // The URL-driven shape is expected to FAIL the healthy assertions. If it
      // passes, the probe cannot tell the two shapes apart.
      observed.ok = observed.ok === false;
      observed.note = observed.ok
        ? "探针在 URL 驱动的对照件上测出了差异（组合被打断）"
        : "探针在 URL 驱动的对照件上**没有**测出差异——探针本身不可信";
      results.push(observed);
    }
  } catch (error) {
    notes.push(`blocked_environment: ${error.message}`);
    results.push({
      id: "probe-run",
      ok: false,
      error: error.message,
      blockedEnvironment: true
    });
  } finally {
    try {
      cdp?.close();
    } catch {
      // ignore
    }
    chrome?.child?.kill("SIGTERM");
    viteProcess?.kill("SIGTERM");
    await sleep(300);
    rmSync(probeHtmlPath, { force: true });
    rmSync(probeEntryPath, { force: true });
    if (userDataDir) rmSync(userDataDir, { recursive: true, force: true });
  }

  const failed = results.filter((result) => result.ok !== true);
  const report = {
    spec: "docs/specs/lucy-20261029-url-driven-input-ime-composition-spec.md §6.3 (SC-17)",
    evidenceKind: "real-browser (system Chrome + CDP Input.imeSetComposition)",
    chromeVersion,
    vitePort: VITE_PORT,
    cdpPort: CDP_PORT,
    compositionSequence: ["zhong", "zhongwen", "中文"],
    notes,
    results,
    passed: failed.length === 0,
    failedCount: failed.length
  };

  mkdirSync(outputDir, { recursive: true });
  writeFileSync(
    path.join(outputDir, "ime-composition-probe-output.json"),
    `${JSON.stringify(report, null, 2)}\n`,
    "utf8"
  );

  const lines = [];
  lines.push("# 真浏览器 IME 组合探针输出（SC-17）");
  lines.push("");
  lines.push(`- Chrome: ${chromeVersion ?? "unknown"}`);
  lines.push(`- 组合序列: zhong → zhongwen → 中文`);
  lines.push(`- 通过: ${results.length - failed.length} / ${results.length}`);
  lines.push("");
  lines.push("| 输入框 | 页面 | compositionstart | 最终 DOM 值 | value setter（该框） | 焦点保持 | 期望 | 结论 |");
  lines.push("|---|---|---|---|---|---|---|---|");
  for (const result of results) {
    lines.push(
      `| ${result.id} | ${result.page ?? "-"} | ${result.compositionStarts ?? "-"} | ${result.finalValue ?? "-"} | ${result.valueWrites ?? "-"} | ${result.focusKept === true ? "是" : result.focusKept === false ? "否" : "-"} | ${result.expected ?? "-"} | ${result.ok ? "PASS" : `FAIL${result.error ? `（${result.error}）` : ""}`} |`
    );
  }
  if (notes.length) {
    lines.push("");
    lines.push("## 备注");
    for (const note of notes) lines.push(`- ${note}`);
  }
  writeFileSync(path.join(outputDir, "ime-composition-probe-output.txt"), `${lines.join("\n")}\n`, "utf8");
  writeFileSync(
    path.join(outputDir, "chrome-version.txt"),
    `${chromeVersion ?? "unknown"}\n`,
    "utf8"
  );

  console.log(lines.join("\n"));
  if (failed.length > 0) process.exit(1);
}

run();
