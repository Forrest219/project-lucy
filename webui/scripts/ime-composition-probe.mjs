/**
 * 真浏览器 IME 组合探针（CDP）
 *
 * Spec: docs/specs/lucy-20261029-url-driven-input-ime-composition-spec.md
 *   §6.3 SC-17（真实浏览器验收）
 *
 * ── 为什么必须有真浏览器 ────────────────────────────────────────────────────
 *
 * jsdom 没有真实 IME，也没有「旧 URL 值渲染一帧」的中间态，因此**不可复现**
 * 本缺陷（Spec §1.2 已实测）。任何以 jsdom 为唯一手段的验收都不能证明缺陷已
 * 修复。本探针用系统 Chrome + CDP `Input.imeSetComposition` 驱动真实组合序列。
 *
 * ── 探针做什么 ──────────────────────────────────────────────────────────────
 *
 * 对 13 处受控输入框逐处：
 *   1. `compositionstart` 计数 **= 1**（不得 > 1）；
 *   2. 最终 DOM 值 **== "中文"**（不得出现拼接）；
 *   3. 组合期间 `HTMLInputElement.prototype.value` setter 对**该输入框**的调用
 *      次数 **= 0**；
 *   4. `document.activeElement` 仍是该输入框（焦点保持）。
 *
 * 同一页面放一个**本地 state 驱动的对照输入框**，证明探针本身能测出差异。
 *
 * ── 运行 ────────────────────────────────────────────────────────────────────
 *
 *   node webui/scripts/ime-composition-probe.mjs
 *
 * 脚本会临时生成一个 vite 入口挂载**真实页面组件**，跑完即删；产物落在
 * `inbox/ime-composition/probe/`。
 */

