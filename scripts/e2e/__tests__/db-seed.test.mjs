// B3 measured DB seed setup (Spec §6.2, §6.4; --apply-db).
//
// Tests prove the producer's contract:
//   - missing inputs (incl. isolation id, password files, ownerRole) yield a
//     refusal, NOT applied=true;
//   - the seed-data.sql text digest must match the run's expected seedSqlDigest;
//   - the independent dataset digest (computed against the actual DB rows) must
//     match the run's expected datasetDigest;
//   - a successful apply sets `measurement.applied = true` only after a real
//     seed-data.sql run, per-role SELECT GRANTs, a REVOKE FROM PUBLIC, successful
//     readonly probes of every seeded table AS EVERY ROLE returning a positive
//     rowcount, and a denied write attempt against every role on every database;
//   - SQL generated by the producer is REAL PostgreSQL: CREATE ROLE LOGIN
//     NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT, GRANT USAGE / SELECT on the
//     schema / specific tables, REVOKE FROM PUBLIC, NOT SQL Server (no CREATE LOGIN
//     / CREATE USER FOR LOGIN / SCHEMA::). The mock executor inspects the SQL
//     text so a regression in the dialect is caught at the contract layer.

import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, it } from "node:test";
import { computeDatasetDigest, generateDataset, renderSeedSql } from "../../../examples/security-e2e/gold/compute-gold.mjs";
import { applySyntheticDbSeed, computeDatasetDigest as exportedComputeDatasetDigest, splitSeedDataSql } from "../lib/db-seed.mjs";

const SEED = "0123456789abcdef0123456789abcdef";
const ISO = "iso1234567890ab";
const READER_ROLE = `lucy_e2e_reader_${ISO}`;
const FIN_NAME = `lucy_e2e_fin_${ISO}`;
const SALES_NAME = `lucy_e2e_sales_${ISO}`;

const dataset = generateDataset(SEED);
const SEED_DATA_SQL = renderSeedSql(dataset);
const SEED_SQL_DIGEST = `sha256:${createHash("sha256").update(SEED_DATA_SQL).digest("hex")}`;
const DATASET_DIGEST = computeDatasetDigest(dataset);

function tempDir() {
  return mkdtempSync(path.join(tmpdir(), "lucy-db-seed-"));
}

function fakeRun({
  host = "127.0.0.1",
  port = 5432,
  name = `lucy_e2e_${ISO}`,
  readonlyRoles = [READER_ROLE],
  checker = null,
  runOwnerIsolationId = ISO,
  ownerRole = "postgres",
  ownerPasswordFile = null,
  passwordFile = null,
  seedSqlDigest = SEED_SQL_DIGEST,
  datasetDigest = DATASET_DIGEST
} = {}) {
  const runDir = mkdtempSync(path.join(tmpdir(), "lucy-db-run-"));
  const checkerDir = checker ?? runDir;
  mkdirSync(checkerDir, { recursive: true });
  writeFileSync(path.join(checkerDir, "seed-data.sql"), SEED_DATA_SQL);
  // `passwordFile` is a SINGLE file path (mode 0600), the per-run reader password.
  // prepare-environment writes the same per-run password to `<runDir>/checker/secrets/db-reader.password`.
  const pf = passwordFile ?? path.join(runDir, "db-reader.password");
  writeFileSync(pf, "very-secret-password-1234", { mode: 0o600 });
  const opf = ownerPasswordFile ?? path.join(runDir, "db-owner.password");
  writeFileSync(opf, "owner-secret-password-1234", { mode: 0o600 });
  return {
    runId: "r1",
    instanceId: "i1",
    paths: { runDir, checker: checkerDir },
    db: {
      host, port, name, readonlyRoles, runOwnerIsolationId,
      passwordFile: pf,
      ownerRole,
      ownerPasswordFile: opf,
      seedSqlDigest,
      datasetDigest
    }
  };
}

function makeFakeExecuteSql({ counts = { "analytics.marketing_daily": 336, "analytics.orders_masked": 24 }, datasets = null } = {}) {
  const calls = [];
  // The dataset digest verification in applySyntheticDbSeed reads rows back from
  // both databases; the mock must return a canonical row set that matches the
  // gold dataset (or whatever the test wants). When no override is given we
  // synthesize a minimal correct dataset so the digest check passes.
  const baseDataset = datasets ?? generateReadbackDataset();
  return {
    calls,
    fn: async ({ sql }) => {
      calls.push({ sql: String(sql).trim() });
      // CREATE DATABASE / CREATE ROLE: succeed silently
      if (/^CREATE\s+(ROLE|DATABASE)/i.test(sql)) return [];
      // DDL: CREATE TABLE / VIEW / SCHEMA: succeed silently
      if (/^CREATE\s+(TABLE|VIEW|SCHEMA)/i.test(sql)) return [];
      // GRANT / REVOKE: succeed silently. The DDL is multi-statement (CREATE
      // SCHEMA + CREATE TABLE + REVOKE FROM PUBLIC + GRANT USAGE/SELECT), so we
      // check for the keyword anywhere in the text, not just at the start.
      if (/\bGRANT\s+/i.test(sql)) return [];
      if (/\bREVOKE\s+/i.test(sql)) return [];
      // INSERTs: succeed silently.
      if (/^INSERT\s+INTO/i.test(sql)) return [];
      // Readback of analytics.marketing_daily: return BOTH the ACTUAL and the
      // FORECAST marketing rows. The seed-data.sql now inserts both surfaces
      // (C3/C5 forecast rows share the same table) so the readback returns the
      // full table; the producer then splits by channel prefix. Return rows in
      // the same canonical (day, region, channel) order the gold dataset expects.
      if (/FROM\s+analytics\.marketing_daily\s+ORDER\s+BY\s+day/i.test(sql)) {
        const all = [...baseDataset.marketing, ...(baseDataset.marketingForecast ?? [])];
        return all.map((row) => ({
          day: row.day,
          region: row.region,
          channel: row.channel,
          spend_cents: row.spendCents,
          new_customers: row.newCustomers
        }));
      }
      // Readback of analytics.orders: return the gold rows in canonical order. The
      // producer reads both fin-db and sales-db; we return the dataset's matching
      // half each time (the SELECT statement does not carry the DB name, so the
      // mock returns finOrders first and salesOrders on subsequent calls).
      if (/FROM\s+analytics\.orders\s+ORDER\s+BY\s+order_id/i.test(sql)) {
        // Caller's first readback is fin, second is sales.
        const seen = calls.filter((c) => /FROM\s+analytics\.orders\s+ORDER\s+BY\s+order_id/i.test(c.sql)).length;
        const rows = seen <= 1 ? baseDataset.finOrders : baseDataset.salesOrders;
        return rows.map((row) => ({
          order_id: row.orderId,
          region: row.region,
          amount_cents: row.amountCents,
          customer_email: row.customerEmail,
          note: row.note
        }));
      }
      // COUNT(*) probes: return a deterministic positive rowcount per table.
      // The producer quotes identifiers (`"analytics"."marketing_daily"`), so we
      // match the qualified name with optional double quotes between the parts.
      const countMatch = /FROM\s+(?:"?)([a-z_]+)(?:"?)\s*\.\s*(?:"?)([a-z_]+)(?:"?)/i.exec(sql);
      if (countMatch && /COUNT\(\*\)/i.test(sql)) {
        const key = `${countMatch[1]}.${countMatch[2]}`;
        return [{ n: counts[key] ?? 0 }];
      }
      // BEGIN/INSERT/ROLLBACK: in the unit-test mock, we simulate the engine's
      // refusal of the INSERT (the ROLLBACK is just bookkeeping).
      if (/BEGIN[\s\S]*INSERT/i.test(sql) && /ROLLBACK/i.test(sql)) {
        throw new Error("permission denied for table orders");
      }
      return [];
    }
  };
}

function generateReadbackDataset() {
  // Build a canonical readback dataset that has the SAME digest as the gold
  // dataset the producer compares against. We use the gold generator directly so
  // both halves of the digest computation produce identical bytes.
  const gold = generateDataset(SEED);
  return {
    marketing: gold.marketing,
    marketingForecast: gold.marketingForecast ?? [],
    finOrders: gold.finOrders,
    salesOrders: gold.salesOrders
  };
}

describe("B3 db-seed: refused inputs never set applied=true", () => {
  it("refuses when host/port are missing", async () => {
    const run = fakeRun();
    run.db.host = null;
    run.db.port = null;
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local", executeSql: makeFakeExecuteSql().fn
    });
    assert.equal(ok, false);
    assert.equal(measurement.applied, false);
    assert.match(measurement.problems.join(" "), /host\/port/);
  });

  it("refuses when readonlyRoles is empty", async () => {
    const run = fakeRun({ readonlyRoles: [] });
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local", executeSql: makeFakeExecuteSql().fn
    });
    assert.equal(ok, false);
    assert.match(measurement.problems.join(" "), /readonlyRoles/);
  });

  it("refuses when runOwnerIsolationId is missing (disposable scope guard)", async () => {
    const run = fakeRun({ runOwnerIsolationId: null });
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local", executeSql: makeFakeExecuteSql().fn
    });
    assert.equal(ok, false);
    assert.match(measurement.problems.join(" "), /runOwnerIsolationId/);
  });

  it("refuses when reader passwordFile is missing (no password in env or run.json)", async () => {
    const run = fakeRun({ passwordFile: null });
    run.db.passwordFile = null;
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local", executeSql: makeFakeExecuteSql().fn
    });
    assert.equal(ok, false);
    assert.match(measurement.problems.join(" "), /passwordFile|reader password file/);
  });

  it("refuses when ownerRole / ownerPasswordFile are missing", async () => {
    const run = fakeRun({ ownerRole: null, ownerPasswordFile: null });
    run.db.ownerRole = null;
    run.db.ownerPasswordFile = null;
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local", executeSql: makeFakeExecuteSql().fn
    });
    assert.equal(ok, false);
    assert.match(measurement.problems.join(" "), /ownerRole|ownerPasswordFile/);
  });

  it("refuses when seed-data.sql is missing", async () => {
    const run = fakeRun();
    rmSync(path.join(run.paths.checker, "seed-data.sql"));
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local", executeSql: makeFakeExecuteSql().fn
    });
    assert.equal(ok, false);
    assert.match(measurement.problems.join(" "), /seed-data\.sql/);
  });

  it("refuses when executeSql is missing", async () => {
    const run = fakeRun();
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local"
    });
    assert.equal(ok, false);
    assert.match(measurement.problems.join(" "), /executeSql/);
  });

  it("refuses when the seed-data.sql text digest does not match run.db.seedSqlDigest", async () => {
    const run = fakeRun({ seedSqlDigest: "sha256:" + "0".repeat(64) });
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local", executeSql: makeFakeExecuteSql().fn
    });
    assert.equal(ok, false);
    assert.match(measurement.problems.join(" "), /digest mismatch/);
  });

  it("refuses when the measured dataset digest does not match run.db.datasetDigest", async () => {
    // Use a deliberately WRONG counts so the readback digest differs from the run's digest.
    const run = fakeRun({ datasetDigest: "sha256:" + "1".repeat(64) });
    const exec = makeFakeExecuteSql({ counts: { "analytics.marketing_daily": 0, "analytics.orders_masked": 0 } });
    const { ok, measurement } = await applySyntheticDbSeed({ run, runMode: "local", executeSql: exec.fn });
    assert.equal(ok, false);
    assert.match(measurement.problems.join(" "), /dataset digest mismatch|non-positive count/);
  });
});

describe("B3 db-seed: a successful apply sets measurement.applied=true", () => {
  it("issues real PostgreSQL DDL/GRANT/REVOKE and per-role probes + write denials across both databases", async () => {
    const run = fakeRun();
    const exec = makeFakeExecuteSql();
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local", executeSql: exec.fn
    });
    assert.equal(ok, true, `problems: ${measurement.problems.join(" | ")}`);
    assert.equal(measurement.applied, true);
    assert.equal(measurement.seedApplied, true);
    assert.equal(measurement.seedSqlDigestMeasured, SEED_SQL_DIGEST);
    assert.equal(measurement.finDatabase, FIN_NAME);
    assert.equal(measurement.salesDatabase, SALES_NAME);
    assert.equal(measurement.readerRole, READER_ROLE);
    // 1 role * 3 probe tables (marketing_daily fin + orders_masked fin + orders_masked sales)
    assert.equal(measurement.readonlyProbes.length, 3);
    // 1 role * 2 databases
    assert.equal(measurement.writeAttemptsDenied, 2);

    // Real PostgreSQL syntax, not SQL Server: no CREATE LOGIN / CREATE USER FOR LOGIN.
    const allSql = exec.calls.map((c) => c.sql).join("\n");
    assert.ok(!/CREATE\s+LOGIN/i.test(allSql), "must NOT emit SQL Server `CREATE LOGIN`");
    assert.ok(!/FOR\s+LOGIN/i.test(allSql), "must NOT emit SQL Server `CREATE USER FOR LOGIN`");
    assert.ok(!/SCHEMA::/i.test(allSql), "must NOT emit SQL Server `SCHEMA::` syntax");
    // Real PostgreSQL syntax: CREATE ROLE LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT
    const createRole = exec.calls.find((c) => /^CREATE\s+ROLE\s+/i.test(c.sql));
    assert.ok(createRole, "CREATE ROLE is issued");
    assert.match(createRole.sql, /LOGIN/i);
    assert.match(createRole.sql, /NOSUPERUSER/i);
    assert.match(createRole.sql, /NOCREATEDB/i);
    assert.match(createRole.sql, /NOCREATEROLE/i);
    assert.match(createRole.sql, /NOINHERIT/i);
    // CREATE DATABASE per-run
    const dbs = exec.calls.filter((c) => /^CREATE\s+DATABASE\s+/i.test(c.sql));
    assert.equal(dbs.length, 2, "two per-run databases are created");
    assert.ok(dbs.some((c) => c.sql.includes(FIN_NAME)));
    assert.ok(dbs.some((c) => c.sql.includes(SALES_NAME)));
    // GRANT USAGE / GRANT SELECT issued per database — the DDL is multi-statement,
    // so we inspect the SQL TEXT for the keyword (not just the call count).
    const ddlSql = exec.calls.map((c) => c.sql).join("\n");
    const grantCount = (ddlSql.match(/\bGRANT\s+/gi) ?? []).length;
    // fin-db: GRANT USAGE + GRANT SELECT marketing_daily + GRANT SELECT orders_masked = 3
    // sales-db: GRANT USAGE + GRANT SELECT orders_masked = 2
    assert.ok(grantCount >= 5, `at least USAGE + SELECT grants per database are issued (got ${grantCount})`);
    // REVOKE FROM PUBLIC (default-privilege hygiene) is issued
    const revokes = (ddlSql.match(/\bREVOKE\s+[^;]*FROM\s+PUBLIC/gi) ?? []);
    assert.ok(revokes.length >= 1, "REVOKE FROM PUBLIC is issued");
    // Per-role write attempt (BEGIN/INSERT/ROLLBACK) is issued against both DBs.
    const probes = exec.calls.filter((c) => /BEGIN/i.test(c.sql) && /INSERT\s+INTO\s+"?analytics"?\."?orders"?/i.test(c.sql));
    assert.ok(probes.length >= 2, `write-denial INSERT attempted on both databases (got ${probes.length})`);
  });

  it("stays applied=false when a per-role write attempt did NOT raise a permission-denied error", async () => {
    const run = fakeRun();
    const exec = {
      calls: [],
      fn: async ({ sql }) => {
        exec.calls.push({ sql: String(sql).trim() });
        if (/COUNT\(\*\)/i.test(sql)) return [{ n: 3 }];
        if (/\bGRANT\s+/i.test(sql)) return [];
        if (/\bREVOKE\s+/i.test(sql)) return [];
        if (/^CREATE\s+(ROLE|DATABASE|TABLE|VIEW|SCHEMA)/i.test(sql)) return [];
        if (/^INSERT\s+INTO/i.test(sql)) return [];
        // Readback queries: return the gold dataset so the digest check passes.
        if (/FROM\s+analytics\.marketing_daily\s+ORDER\s+BY\s+day/i.test(sql)) {
          const gold = generateDataset(SEED);
          const all = [...gold.marketing, ...(gold.marketingForecast ?? [])];
          return all.map((row) => ({
            day: row.day, region: row.region, channel: row.channel,
            spend_cents: row.spendCents, new_customers: row.newCustomers
          }));
        }
        if (/FROM\s+analytics\.orders\s+ORDER\s+BY\s+order_id/i.test(sql)) {
          const gold = generateDataset(SEED);
          const seen = exec.calls.filter((c) => /FROM\s+analytics\.orders\s+ORDER\s+BY\s+order_id/i.test(c.sql)).length;
          const rows = seen <= 1 ? gold.finOrders : gold.salesOrders;
          return rows.map((row) => ({
            order_id: row.orderId, region: row.region, amount_cents: row.amountCents,
            customer_email: row.customerEmail, note: row.note
          }));
        }
        // The write attempt SUCCEEDS — bad; the role was NOT actually readonly.
        if (/BEGIN/i.test(sql) && /INSERT\s+INTO\s+analytics\.orders/i.test(sql)) return [{ ok: 1 }];
        return [];
      }
    };
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local", executeSql: exec.fn
    });
    assert.equal(ok, false, "applied must stay false when the readonly contract did not hold");
    assert.equal(measurement.applied, false);
    assert.equal(measurement.writeAttemptsDenied, 0);
    assert.match(measurement.problems.join(" "), /readonly write attempt|not actually readonly|denied/);
  });

  it("stays applied=false when a per-role probe returns a zero rowcount", async () => {
    const run = fakeRun();
    const exec = makeFakeExecuteSql({ counts: { "analytics.marketing_daily": 0, "analytics.orders_masked": 0 } });
    const { ok, measurement } = await applySyntheticDbSeed({
      run, runMode: "local", executeSql: exec.fn
    });
    assert.equal(ok, false);
    assert.equal(measurement.applied, false);
    assert.match(measurement.problems.join(" "), /non-positive count/);
  });
});

describe("B3 db-seed: per-run dataset digest is an INDEPENDENT row readback, not the SQL hash", () => {
  it("computes a stable dataset digest from a deterministic gold dataset", () => {
    const a = exportedComputeDatasetDigest(generateDataset(SEED));
    const b = exportedComputeDatasetDigest(generateDataset(SEED));
    const c = exportedComputeDatasetDigest(generateDataset("ffffffffffffffffffffffffffffffff"));
    assert.equal(a, b, "dataset digest is deterministic for the same seed");
    assert.notEqual(a, c, "dataset digest differs for a different seed");
  });

  it("detects 'wrong values, same rowcount' — a hash mismatch fails the apply even when counts match", () => {
    // Build a gold dataset whose row order matches the seed but whose VALUES are wrong.
    const dataset = generateDataset(SEED);
    const tampered = {
      ...dataset,
      finOrders: dataset.finOrders.map((r, i) => ({ ...r, amountCents: i + 1 })) // wrong amounts
    };
    const goldDigest = computeDatasetDigest(dataset);
    const tamperedDigest = computeDatasetDigest(tampered);
    assert.notEqual(goldDigest, tamperedDigest, "tampered values MUST produce a different dataset digest");
  });
});